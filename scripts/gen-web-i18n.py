#!/usr/bin/env python3
"""Regenerate the web UI string table from the shared i18n single source.

shared/i18n/{zh,en}.json is the product's string authority (AGENTS.md /
#141). The web app never hardcodes user-facing text: this script emits
apps/desktop/src/i18n.ts with both tables and a tiny {0}-placeholder
formatter. Run via `pnpm gen:i18n`; CI checks the output is current.
"""
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "apps" / "desktop" / "src" / "i18n.ts"


def main() -> int:
    tables = {}
    for lang in ("zh", "en"):
        src = ROOT / "shared" / "i18n" / f"{lang}.json"
        tables[lang] = json.loads(src.read_text(encoding="utf-8"))
    if set(tables["zh"]) != set(tables["en"]):
        missing = set(tables["zh"]) ^ set(tables["en"])
        print(f"i18n key mismatch between zh/en: {sorted(missing)}", file=sys.stderr)
        return 1

    lines = [
        "// GENERATED by scripts/gen-web-i18n.py from shared/i18n/*.json.",
        "// Do not edit by hand — edit the shared single source and regenerate.",
        "/* eslint-disable */",
        "",
        "export type Lang = 'zh' | 'en';",
        "",
    ]
    for lang in ("zh", "en"):
        lines.append(f"const {lang}: Record<string, string> = {{")
        for key, value in tables[lang].items():
            lines.append(f"  {json.dumps(key)}: {json.dumps(value, ensure_ascii=False)},")
        lines.append("};")
        lines.append("")
    lines += [
        "const TABLES: Record<Lang, Record<string, string>> = { zh, en };",
        "",
        "let current: Lang = 'zh';",
        "",
        "export function setLang(lang: Lang): void { current = lang; }",
        "export function getLang(): Lang { return current; }",
        "",
        "/** Resolve the UI language from the engine setting (system → locale). */",
        "export function resolveLang(setting: string): Lang {",
        "  if (setting === 'zh-CN' || setting === 'zh') return 'zh';",
        "  if (setting === 'en') return 'en';",
        "  const nav = typeof navigator !== 'undefined' ? navigator.language : 'en';",
        "  return nav.toLowerCase().startsWith('zh') ? 'zh' : 'en';",
        "}",
        "",
        "/** t('key', a0, a1…) — {0}-style placeholders, zh fallback for gaps. */",
        "export function t(key: string, ...args: (string | number)[]): string {",
        "  const raw = TABLES[current][key] ?? TABLES.zh[key] ?? key;",
        "  return raw.replace(/\\{(\\d+)\\}/g, (m, i) => {",
        "    const v = args[Number(i)];",
        "    return v === undefined ? m : String(v);",
        "  });",
        "}",
        "",
    ]
    OUT.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"i18n.ts written: {len(tables['zh'])} keys x 2 langs")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())